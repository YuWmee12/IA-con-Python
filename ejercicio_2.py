#variables emteras
NUMERO=24
print(NUMERO)

#variables de texto
SALUDO='Hola'
print(SALUDO)
 
#variables de tipo flotante
PRECIO=24.5
print(PRECIO)

#variables de tipo booleano
ES_MAYOR_DE_EDAD=True
print(ES_MAYOR_DE_EDAD)
 
#variables de tipo lista 
lISTA=[1,2,6,4,5]
print(lISTA) #entre corchetes puedes elegir el numero de la lista que quieres imprimir
print(lISTA[2])

#variables de tipo tupla
TUPLA=(1,2,3,4,5)
print(TUPLA) #entre parentesis puedes elegir el numero de la tupla que quieres imprimir
#que es una tupla? 
#una tupla es una lista inmutable, lo que significa que no se puede modificar después de su creación

#variables de tipo diccionario
DICCIONARIO={'nombre':'mayu','edad':24,'pais':'México'}
print(DICCIONARIO) #entre llaves puedes elegir la clave del diccionario que quieres imprimir    
print(DICCIONARIO['pais'])

#variable de tipo conjunto
CONJUNTO={1,2,3,4,5}
print(CONJUNTO) #entre llaves puedes elegir el numero del conjunto que quieres imprimir
print(CONJUNTO & {3,4,5}) #intersección de conjuntos